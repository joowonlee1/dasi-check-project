import streamlit as st


# 브라우저 탭 제목과 화면 구성을 설정한다.
st.set_page_config(
    page_title="다시확인",
    page_icon="☎️",
    layout="centered"
)


def show_home():
    """프로젝트 소개와 앞으로 만들 기능을 표시한다."""

    st.title("☎️ 다시확인")
    st.subheader("익숙한 번호라도, 한 번 더 확인해요.")

    st.write(
        "가족 사칭 전화부터 의심 문자와 링크까지, "
        "다양한 상황에서 확인하고 대응하는 방법을 "
        "연습하는 예방 교육 앱입니다."
    )

    st.info(
        "현재는 첫 화면을 만드는 단계입니다. "
        "아래 기능은 순서대로 구현할 예정입니다."
    )

    st.divider()

    st.header("왜 만들었나요?")

    st.write(
        "가족의 이름이나 번호로 표시되는 연락을 받으면 "
        "상대를 가족이라고 믿기 쉽습니다. "
        "이 앱은 상대를 믿게 된 단서와 실제 확인한 사실을 "
        "구분하고, 대응 행동을 연습하도록 돕고자 합니다."
    )

    st.header("어떤 기능을 만들까요?")

    # 같은 형태의 정보를 리스트 안에 저장한다.
    features = [
        (
            "1. 신종 보이스피싱 모의 체험",
            "가상 전화와 후속 문자에 대응하고 "
            "체험 종료 후 내 행동을 돌아봅니다."
        ),
        (
            "2. 모의 피싱 대화 연습",
            "힌트와 설명을 받으며 "
            "확인·거절·도움 요청 방법을 연습합니다."
        ),
        (
            "3. 문자 체험 퀴즈",
            "가상 문자 3문항을 풀고 "
            "정답과 해설을 확인합니다."
        ),
        (
            "4. 의심 URL 확인 도우미",
            "링크를 입력하면 주소 구조와 "
            "추가 확인이 필요한 특징을 보여 줍니다."
        ),
        (
            "5. 개념·최신 공식 통계",
            "관련 개념과 공식 통계를 "
            "출처 및 집계 기간과 함께 살펴봅니다."
        )
    ]

    # 반복문으로 기능 이름과 설명을 차례대로 표시한다.
    for title, description in features:
        st.subheader(title)
        st.write(description)

    st.divider()

    st.header("이 앱의 차별점")

    st.markdown(
        """
        - 전화에서 후속 문자까지 **연결된 상황**을 체험합니다.
        - 사용자의 **대응 행동과 판단 이유**를 함께 살펴봅니다.
        - 부족했던 부분을 연습·퀴즈·URL 확인으로 연결합니다.
        """
    )

    st.caption(
        "교육용 가상 사례를 사용할 예정입니다. "
        "실제 번호 위조나 음성 합성을 탐지하는 앱은 아닙니다."
    )


# 위에서 정의한 함수를 실행한다.
show_home()
