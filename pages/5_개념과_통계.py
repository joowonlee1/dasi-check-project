def concept_cards(rows):
    cards = "".join(
        f'<div class="cc"><div class="cc-top"><span class="cc-ic">{icon}</span><b>{escape(name)}</b></div>'
        f'<p>{escape(meaning)}</p><div class="cc-ok">✅ {escape(check)}</div>'
        f'<details class="cc-more"><summary>자세히 보기</summary>{escape(DETAILS.get(name, ""))}</details>'
        f'<div class="cc-game">🎮 {escape(where)}</div></div>'
        for _, icon, name, meaning, check, where in rows
    )
    return '<div class="cc-grid">' + cards + "</div>"


